"""Data Core 对消费者公开的只读查询端口。"""

from __future__ import annotations

from typing import Any, Protocol, Sequence

from hextech.contracts.identifiers import AugmentId, ChampionId, ItemId


class SnapshotViewPort(Protocol):
    def status(self) -> dict[str, Any]: ...
    def get_champion(self, champion_id: ChampionId) -> dict[str, Any] | None: ...
    def get_champions(self) -> list[dict[str, Any]]: ...
    def resolve_augment(self, value: object) -> dict[str, Any] | None: ...
    def get_combo_stats(self, champion_id: ChampionId, augment_id: AugmentId) -> dict[str, Any] | None: ...
    def get_item(self, item_id: ItemId) -> dict[str, Any] | None: ...
    def get_item_recommendations(self, champion_id: ChampionId) -> Sequence[dict[str, Any]]: ...


class SnapshotQueryPort(Protocol):
    def open_view(self) -> SnapshotViewPort: ...
